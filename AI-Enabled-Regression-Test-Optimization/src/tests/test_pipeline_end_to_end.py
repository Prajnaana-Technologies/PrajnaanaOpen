"""run_pipeline, for real: the only fake is the board.

tests/test_governance.py::_pipeline_harness drives run_pipeline with
generate_tests, govern, run_suite and the KPI store all replaced by fakes.
That proves the orchestration bookkeeping -- who is called, in what order,
with what -- and nothing at all about the path a run takes on the bench:
no module is written, nothing is compiled, no assertion is executed, and
the verdict the pipeline reports is a string the harness handed it.

Here everything is the product's own code:

  * generate_tests writes the planner-selected module, for real, and
    build_canonical_suite turns a requirement document into the second
    module through canonical.build and generate_from_canonical.generate.
  * govern runs the real acceptance rules over the real generated bytes.
  * run_suite really invokes pytest on both files, and the verdict comes
    back from what pytest reported.
  * kpi.record_run really writes the history entry.

The only fake is the board, because there is none: FakeBLEDevice stands in
for RealBLEDevice. It answers the same calls, returns plausible telemetry,
and echoes audio back through a compressor-shaped gain, so the
hardware-touching tests in the generated modules either pass against it or
skip with a reason -- which is what they would do on the bench.

Two settings are forced rather than faked: the planner runs in rules mode
(HA_AI=rules), so no model is called and no key is needed, and
HA_TEST_SECONDS is an eighth of a second, which is one burst.

Everything written goes under tmp_path: the writable root, the log
directory, both generated modules and the approvals store are all
redirected, so a run here leaves nothing behind and reads nothing a
previous run left.
"""

