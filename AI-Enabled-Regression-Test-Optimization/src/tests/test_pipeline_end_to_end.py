# One service holding the two characteristics ble_audio names. Firmware
# that does not implement the loopback is firmware that does not publish
# the processed-audio notify characteristic, so that is how "no loopback"
# is modelled: the characteristic is absent from the table, which is what
# tools/ble_probe.py would report of such a board.
FAKE_SERVICE_UUID = "12345678-1234-5678-1234-56789abcdef0"

# The capability probe as the product defines it, bound now: the staged
# fixture replaces ble_audio.RealBLEDevice with a factory for the fake, so
# reading the attribute later would find the stand-in and prove nothing.
_REAL_LOOPBACK_PROBE = ble_audio.RealBLEDevice.supports_audio_loopback
_REAL_LOOPBACK_CHARACTERISTIC = ble_audio.RealBLEDevice.loopback_characteristic


class _FakeCharacteristic:

    def __init__(self, uuid, properties):
        self.uuid = uuid
        self.properties = properties


class _FakeService:

    def __init__(self, uuid, characteristics):
        self.uuid = uuid
        self.characteristics = characteristics


class _FakeGATTTable:
    """The part of bleak's BleakGATTServiceCollection the probe reads."""

    def __init__(self, device):
        self._device = device

    def _characteristics(self):
        characteristics = [
            _FakeCharacteristic(ble_audio.WRITE_CHAR_UUID,
                                ["write-without-response"]),
        ]

        if self._device.loopback:
            characteristics.append(_FakeCharacteristic(
                ble_audio.NOTIFY_CHAR_UUID,
                getattr(self._device, "notify_properties", ["notify"])))

        return characteristics

    def get_characteristic(self, specifier):
        wanted = str(specifier).lower()

        for characteristic in self._characteristics():
            if characteristic.uuid.lower() == wanted:
                return characteristic

        return None

    def __iter__(self):
        return iter([_FakeService(FAKE_SERVICE_UUID, self._characteristics())])


class _FakeClient:
    """The bleak client surface ble_audio reaches through itself.

    The capability probe is the only thing that uses it: every other call
    the generated modules make is answered by FakeBLEDevice directly. So
    "writes" counts exactly what the probe wrote to the board, and
    "table_reads" what it read from the GATT table -- which is how the
    tests below can say what the capability was decided from.
    """

    def __init__(self, device):
        self._device = device
        self.mtu_size = 247
        self.writes = 0
        self.table_reads = 0

        # bleak raises when the table cannot be read on this link -- the
        # link dropped, or discovery has not finished. Unknown, which is
        # not the same answer as "this firmware has no loopback".
        self.table_error = False

    @property
    def is_connected(self):
        return self._device.connected

    @property
    def services(self):
        if self.table_error or not self._device.connected:
            raise RuntimeError("Service Discovery has not been performed yet")

        self.table_reads += 1

        return _FakeGATTTable(self._device)

    async def write_gatt_char(self, uuid, data, response=False):
        self.writes += 1

        if self._device.probe_write_error:
            raise RuntimeError("Unreachable: the write was not acknowledged")

        # The echo a working loopback sends back arrives as notifications,
        # whatever wrote the audio.
        if self._device.loopback and self._device.dsp != "silent":
            self._device.processed_audio.extend(bytes(data))


class _StubBleakClient:
    """The bleak surface RealBLEDevice.connect itself reaches for.

    FakeBLEDevice replaces the whole device; this replaces only the client
    underneath a real RealBLEDevice, which is the only way to exercise
    connect().
    """

    def __init__(self, loopback):
        self.loopback = loopback
        self.is_connected = False
        self.notify_failures = 0
        self.mtu_size = 247

    async def connect(self, timeout=None):
        self.is_connected = True

    @property
    def services(self):
        return _FakeGATTTable(self)

    async def start_notify(self, uuid, handler):
        if self.services.get_characteristic(uuid) is None:
            self.notify_failures += 1

            raise RuntimeError(
                "Characteristic {} was not found!".format(uuid))


class _Unpaced:
    """asyncio with the waits taken out.

    connect() sleeps two seconds for the link to stabilise and backs off
    between attempts. Against a stub there is nothing to wait for, and the
    suite should not pay for it.
    """

    def __getattr__(self, name):
        return getattr(asyncio, name)

    async def sleep(self, seconds, *args, **kwargs):
        return await asyncio.sleep(0)


class FakeBLEDevice:
    """A stand-in for RealBLEDevice with no radio behind it.

    It implements the surface the generated modules and
    regression/measurements.py actually call. Three behaviours matter:

    loopback -- whether this firmware implements the loopback at all,
        which means whether NOTIFY_CHAR_UUID is in the GATT table above.
        False is the honest answer for firmware without the echo, and
        makes every audio test skip rather than fail, exactly as
        require_loopback intends.

    dsp -- what the echo does to the audio. "compressor" applies less gain
        to loud input than to quiet input, which is what a hearing aid
        does and what test_compression_curve checks for. "passthrough"
        returns the input untouched: a device whose DSP has stopped
        working, which the suite is supposed to catch. "silent" notifies
        nothing back although the firmware publishes the characteristic,
        which is what the board does when the DSP hangs, a write fails or
        the reply times out -- the difference between that and
        loopback=False is a failure against a skip, so the two are
        separate settings.

    probe_write_error -- the capability probe's own GATT writes raise. The
        probe runs first thing after connect, so a link still settling
        rejects them while audio streamed a moment later gets through.
        Nothing else in this stand-in writes at that layer.
    """

    # The firmware clamps its WDRC gain to roughly this range; these two
    # sit inside the generated suite's GAIN_MIN/GAIN_MAX window and are far
    # enough apart to satisfy MIN_COMPRESSION_RATIO.
    QUIET_GAIN = 0.85
    LOUD_GAIN = 0.55

    # Full-scale fraction above which the input counts as loud.
    LOUD_RMS = 0.2

    BUILD_ID = "fake-board+0badc0de"

    def __init__(self, loopback=True, dsp="compressor"):
        self.loopback = loopback
        self.dsp = dsp
        self.probe_write_error = False
        self.connected = False
        self.connects = 0
        self.streams = 0
        self.bonded = False
        self._latency_ms = None
        self._battery = 96

        # What RealBLEDevice's capability probe works with, so that the
        # probe exercised here is the product's own rather than a summary
        # of what it is believed to do.
        self.client = _FakeClient(self)
        self.processed_audio = bytearray()
        self._loopback = None

    # ---------------- link ----------------
    @property
    def is_connected(self):
        return self.connected

    async def connect(self):
        self.connects += 1
        self.connected = True

    async def disconnect(self):
        self.connected = False

    def reset_link_counters(self):
        pass

    # ---------------- transfer ----------------
    async def write(self, data):
        if not self.connected:
            await self.connect()

        return len(data)

    def _processed(self, samples):
        if self.dsp == "passthrough":
            return samples

        level = float(np.sqrt(np.mean(np.square(
            samples.astype(np.float64))))) / 32767.0
        gain = self.LOUD_GAIN if level > self.LOUD_RMS else self.QUIET_GAIN

        return np.round(samples.astype(np.float64) * gain).astype(np.int16)

    async def send_audio_stream(self, audio_data, params=None):
        """Echo one burst back, the way the firmware's loopback does.

        Mirrors RealBLEDevice: a float array is scaled to PCM16 first, and
        a burst is capped at MAX_BURST_BYTES, because the device's return
        buffer is that size.
        """
        if not self.connected:
            await self.connect()

        started = time.monotonic()

        if isinstance(audio_data, np.ndarray):
            data = (audio_data.flatten() * 32767).astype(np.int16).tobytes()
        else:
            data = bytes(audio_data)

        data = data[:ble_audio.MAX_BURST_BYTES]
        self.streams += 1

        if not self.loopback or self.dsp == "silent":
            self._latency_ms = None

            return None

        # Let the loop turn, as a real notification would.
        await asyncio.sleep(0)

        samples = np.frombuffer(data, dtype=np.int16)
        self._latency_ms = (time.monotonic() - started) * 1000.0

        return self._processed(samples).tobytes()

    @property
    def last_stream_latency_ms(self):
        return self._latency_ms

    # The product's own probe, run against the fake GATT table above
    # rather than reimplemented here. A fake that answered self.loopback
    # directly cannot see a defect in the probe.
    def loopback_characteristic(self):
        return _REAL_LOOPBACK_CHARACTERISTIC(self)

    async def supports_audio_loopback(self, force=False):
        return await _REAL_LOOPBACK_PROBE(self, force)

    # ---------------- readings ----------------
    async def read_battery(self):
        # Drains a little across a run, so battery_drain is a real number.
        level = self._battery
        self._battery = max(0, self._battery - 1)

        return level

    async def read_memory(self):
        return 0.52

    async def read_power(self):
        return None

    async def measure_sync_latency(self):
        return 11.0

    async def read_retry_count(self):
        return 0

    async def read_build_id(self):
        return self.BUILD_ID

    async def read_telemetry(self):
        return {"memory": 0.52, "sync": 11.0, "retry": 0,
                "battery": self._battery}

    async def read_metrics(self):
        return {"memory": 0.52, "sync": 11.0, "retry": 0,
                "battery": self._battery, "unmeasured": ["power"]}

    # ---------------- security ----------------
    async def pair(self):
        self.bonded = True

        return True

    async def unpair(self):
        self.bonded = False

        return True

    async def read_bond_count(self):
        return 1 if self.bonded else None

    async def is_encrypted(self):
        return self.bonded


