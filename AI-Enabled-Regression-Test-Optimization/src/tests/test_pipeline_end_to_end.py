class _Staged:
    """What a staged run needs to talk about afterwards."""

    def __init__(self, root, planner_module, canonical_module, device):
        self.root = root
        self.planner_module = planner_module
        self.canonical_module = canonical_module
        self.device = device
        self.build_id_reads = []
        self.plans = []

    def source(self, path):
        with open(path, encoding="utf-8") as handle:
            return handle.read()

    def junit(self, run_dir):
        """The records pytest itself wrote, re-read from its XML."""
        return reporting.parse_junit(os.path.join(run_dir, "results.xml"))


def _reset_event_loop():
    policy = asyncio.get_event_loop_policy()

    try:
        loop = policy.get_event_loop()
    except RuntimeError:
        loop = None

    if loop is None or loop.is_closed():
        policy.set_event_loop(policy.new_event_loop())


@pytest.fixture
def staged(tmp_path, monkeypatch):
    """Point every path the pipeline writes to at tmp_path, and fake the board.

    Everything redirected here was resolved once at import time and copied
    into several modules by value, so each holder is set individually --
    patching regression.paths alone would leave the orchestrator writing
    into the checkout.
    """
    generated = tmp_path / "generated"
    generated.mkdir()

    planner_module = generated / "test_ai_generated.py"
    canonical_module = generated / "test_from_canonical.py"
    logs = tmp_path / "logs"

    # The writable root: kpi's history and governance's approvals store both
    # resolve through paths.in_base, which reads this at call time.
    monkeypatch.setattr(paths, "BASE_DIR", str(tmp_path))
    monkeypatch.setattr(paths, "LOGS_DIR", str(logs))
    monkeypatch.setattr(paths, "GENERATED_TEST_PATH", str(planner_module))
    monkeypatch.setattr(paths, "CANONICAL_TEST_PATH", str(canonical_module))

    # The copies taken at import.
    monkeypatch.setattr(generate_tests_module, "GENERATED_TEST_PATH",
                        str(planner_module))
    monkeypatch.setattr(generate_from_canonical, "CANONICAL_TEST_PATH",
                        str(canonical_module))
    monkeypatch.setattr(orchestrator, "GENERATED_TEST_PATH",
                        str(planner_module))
    monkeypatch.setattr(orchestrator, "CANONICAL_TEST_PATH",
                        str(canonical_module))
    monkeypatch.setattr(governance, "GENERATED_TEST_PATH", str(planner_module))
    monkeypatch.setattr(governance, "CANONICAL_TEST_PATH",
                        str(canonical_module))

    device = FakeBLEDevice()

    # Every construction site of the board, in the modules that hold a
    # reference to the class. The conftest.py that generate_tests copies
    # next to the generated modules is imported fresh by the inner pytest
    # run and reads ble_audio.RealBLEDevice then, so patching it there is
    # what puts the fake behind the ble_device fixture.
    monkeypatch.setattr(ble_audio, "RealBLEDevice", lambda: device)
    monkeypatch.setattr(orchestrator, "RealBLEDevice", lambda: device)

    requirements = tmp_path / "REQUIREMENTS.md"
    requirements.write_text(SMALL_REQUIREMENTS, encoding="utf-8")

    note = tmp_path / "RELEASE_NOTES.md"
    note.write_text(
        SMALL_RELEASE_NOTE.format(build_id=FakeBLEDevice.BUILD_ID),
        encoding="utf-8")

    monkeypatch.setenv(orchestrator.REQUIREMENTS_ENV, str(requirements))
    monkeypatch.setenv(orchestrator.RELEASE_NOTE_ENV, str(note))
    monkeypatch.setenv("HA_AI", "rules")

    # The audio tests read the whole stimulus otherwise; an eighth of a
    # second is one burst, which is all the fake echoes in one call.
    monkeypatch.setenv("HA_TEST_SECONDS", "0.125")

    # run_pipeline asks the board for the build id when HA_BUILD_ID is
    # unset, which is the path worth exercising: it must ask exactly once.
    monkeypatch.delenv(orchestrator.BUILD_ID_ENV, raising=False)

    state = _Staged(tmp_path, str(planner_module), str(canonical_module),
                    device)

    real_read_build_id = orchestrator.read_build_id

    def counted_read_build_id():
        value = real_read_build_id()
        state.build_id_reads.append(value)

        return value

    monkeypatch.setattr(orchestrator, "read_build_id", counted_read_build_id)

    # The real generator, with a note taken of every plan it returns. The
    # escalation is the only thing that calls it twice, and the second plan
    # has to be harder than the first -- which is a fact about raise_to, not
    # about the planner making a different choice from the same evidence.
    real_generate_tests = orchestrator.generate_tests

    def recorded_generate_tests(*args, **kwargs):
        plan = real_generate_tests(*args, **kwargs)
        state.plans.append(plan)

        return plan

    monkeypatch.setattr(orchestrator, "generate_tests",
                        recorded_generate_tests)

    # Globals the inner pytest run moves and does not put back.
    saved_path = list(sys.path)
    saved_modules = set(sys.modules)

    yield state

    for name in sorted(set(sys.modules) - saved_modules):
        module = sys.modules.get(name)
        origin = getattr(module, "__file__", None) or ""

        if origin.startswith(str(tmp_path)):
            del sys.modules[name]

    sys.path[:] = saved_path

    # The generated_tests conftest closes the loop it made; leaving a closed
    # loop installed breaks anything later in this session that asks for one.
    _reset_event_loop()


def _compiles(path, source):
    """Compile the generated bytes. Raises SyntaxError if they do not."""
    compile(source, path, "exec")

    return True


def _test_names(source):
    """The test functions a generated module defines."""
    return sorted(
        node.name for node in ast.walk(ast.parse(source))
        if isinstance(node, ast.FunctionDef) and node.name.startswith("test_")
    )


# The measurements that send PCM and read back what the DSP returned, so
# none of them has an answer on a board with no loopback. The other three --
# battery, stack and build_id -- are characteristic reads.
AUDIO_MEASUREMENTS = ("snr", "latency", "compression", "gain_range",
                      "sign_flips", "compressor_timing")


def _tests_needing_audio(source):
    """Every test in a generated module that needs audio to come back.

    Two shapes need it: a test that streams audio, which both generators
    guard with require_loopback, and a test that measures one of
    AUDIO_MEASUREMENTS. Read out of the module rather than listed by name,
    so the assertion below covers whatever the generators emitted and not a
    list that goes stale the next time a scenario is added.
    """
    needed = set()

    for node in ast.walk(ast.parse(source)):
        if not (isinstance(node, ast.FunctionDef)
                and node.name.startswith("test_")):
            continue

        for call in ast.walk(node):
            if not isinstance(call, ast.Call):
                continue

            name = getattr(call.func, "id", None) \
                or getattr(call.func, "attr", None)

            if name == "require_loopback":
                needed.add(node.name)
            elif name == "take" and any(
                    isinstance(argument, ast.Constant)
                    and argument.value in AUDIO_MEASUREMENTS
                    for argument in call.args):
                needed.add(node.name)

    return needed


