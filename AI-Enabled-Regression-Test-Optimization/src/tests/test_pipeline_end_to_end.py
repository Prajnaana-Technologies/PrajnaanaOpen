def test_a_broken_dsp_fails_the_run_escalates_it_and_is_recorded(staged):
    """The verdict has to be able to be "fail", or none of it means anything.

    The board echoes audio back untouched: the link works, the loopback
    works, and the DSP does nothing. That is a regression the generated
    suite exists to catch, so the run must fail, escalate once, re-run, and
    file the failures as defects this run caught.
    """
    staged.device.dsp = "passthrough"

    result = orchestrator.run_pipeline(
        metrics=dict(HEALTHY_METRICS, unmeasured=["power"]),
        change_info="the compressor release constant was retuned",
    )

    records = {r.name: r for r in staged.junit(result["run_dir"])}

    assert records["test_audio_dsp"].status == reporting.FAILED, (
        "a device that echoed the input unchanged passed the DSP test")

    assert result["status"] == "fail"

    # Escalation really happened, and really raised the intensity: the
    # module on disk and the plan the KPI recorded are the escalated ones.
    assert len(staged.plans) == 2, "the failure did not trigger a re-plan"

    first, second = (plan.intensity for plan in staged.plans)

    assert planner.INTENSITIES.index(second) > planner.INTENSITIES.index(
        first), "the escalated plan is no harder than the one that failed"

    assert result["intensity"] == second
    assert 'INTENSITY = "{}"'.format(second) in staged.source(
        staged.planner_module)

    entry = kpi.load_runs()[-1]

    assert entry["status"] == "fail"
    assert entry["failed"] == sum(
        1 for r in records.values()
        if r.status in (reporting.FAILED, reporting.ERROR))
    assert entry["intensity"] == result["intensity"]

    # The failing tests were filed as defects the run caught.
    escapes = kpi.load_escapes()

    assert escapes, "a failing run recorded no defect"
    assert all(e["phase"] == "pre_integration" for e in escapes), escapes


def test_a_loopback_that_stops_replying_fails_the_run(staged):
    """A board that HAS the loopback and stops answering must fail.

    The board here reports the loopback and then notifies nothing back,
    which is what the firmware does when the DSP hangs, a write fails or
    the reply times out -- send_audio_stream returns None for all of them.
    The two silences have opposite verdicts, so the probe decides which one
    this is, and this run must be the failing one.
    """
    staged.device.dsp = "silent"

    result = orchestrator.run_pipeline(
        metrics=dict(HEALTHY_METRICS, unmeasured=["power"]),
        change_info="the compressor release constant was retuned",
    )

    records = {r.name: r for r in staged.junit(result["run_dir"])}

    assert result["status"] == "fail", (
        "a board that reports a loopback and answers nothing was reported "
        "as a passing run")

    # And it is decided from the GATT table, not from an echo. A probe
    # that writes audio and waits for it asks the hung part whether it is
    # there. No write, so nothing the DSP does moves it.
    assert staged.device.client.writes == 0, (
        "the capability probe wrote {} time(s) to a board whose DSP is "
        "hung; a probe the fault can break is not a "
        "capability".format(staged.device.client.writes))
    assert staged.device.client.table_reads > 0, (
        "the GATT table was never read, so the capability was decided "
        "from something else")

    # Nothing anywhere in the run was excused as a missing feature: the
    # probe says the board has it. That skip is the whole bug -- an audio
    # case skipping here is a hung DSP reported as firmware that never had
    # the feature, and a run of them reports pass.
    # The message, not the detail: pytest puts the module's own path in the
    # detail, and this test's tmp_path has "loopback" in its name.
    excused = sorted(r.name for r in records.values()
                     if r.status == reporting.SKIPPED
                     and "loopback" in r.message.lower())

    assert not excused, excused

    # Both modules really exercised the audio and both really failed.
    for module in (staged.planner_module, staged.canonical_module):
        audio = _tests_needing_audio(staged.source(module))

        assert audio, "no audio case in " + module

        failed = sorted(name for name in audio
                        if records[name].status in (reporting.FAILED,
                                                    reporting.ERROR))

        assert failed, "no audio case failed in {}: {}".format(
            module, {name: records[name].status for name in sorted(audio)})

    # A measurement case says what is wrong, rather than blaming a feature
    # the board reports it has.
    measured = [r.name for r in records.values() if "not a gap" in r.message]

    assert measured, "no case reported the silent loopback as a failure"

    # And it was filed as a defect this run caught, like any other failure.
    escapes = kpi.load_escapes()

    assert escapes, "a failing run recorded no defect"
    assert kpi.load_runs()[-1]["status"] == "fail"


def test_a_probe_write_error_is_not_a_missing_feature(staged):
    """A probe that cannot write must not answer "this firmware has none".

    The board publishes the loopback characteristic and its DSP has
    stopped, so every audio case on it is a failure. The capability is
    read from the GATT table, which a failed write cannot change.
    """
    staged.device.probe_write_error = True
    staged.device.dsp = "silent"

    result = orchestrator.run_pipeline(
        metrics=dict(HEALTHY_METRICS, unmeasured=["power"]),
        change_info="the compressor release constant was retuned",
    )

    records = {r.name: r for r in staged.junit(result["run_dir"])}

    assert result["status"] == "fail", (
        "a board whose DSP is dead passed because the capability probe "
        "could not write to it")

    # Nothing was excused as a missing feature: the characteristic is in
    # the table, so this firmware has the loopback whatever the writes did.
    # The message, not the detail: pytest puts the module path in the
    # detail and this test's tmp_path carries the word.
    excused = sorted(r.name for r in records.values()
                     if r.status == reporting.SKIPPED
                     and "loopback" in r.message.lower())

    assert not excused, excused

    # The capability never depends on a write at all, so a write that
    # raises is not an answer about the feature.
    assert staged.device.client.writes == 0, (
        "the capability probe wrote {} time(s), so a write that raises is "
        "still an answer".format(staged.device.client.writes))

    # The silence was reported as a failure, in both generated modules.
    for module in (staged.planner_module, staged.canonical_module):
        audio = _tests_needing_audio(staged.source(module))

        assert audio, "no audio case in " + module

        failed = sorted(name for name in audio
                        if records[name].status in (reporting.FAILED,
                                                    reporting.ERROR))

        assert failed, "no audio case failed in {}: {}".format(
            module, {name: records[name].status for name in sorted(audio)})

    assert kpi.load_escapes(), "a failing run recorded no defect"
    assert kpi.load_runs()[-1]["status"] == "fail"


def test_a_gatt_table_that_cannot_be_read_is_not_an_answer(staged):
    """Unknown is not no.

    The table can fail to read -- the link dropped, discovery has not
    finished. The probe raises, which pytest reports as a failure, and the
    reason names the read rather than the firmware.
    """
    device = staged.device
    loop = asyncio.new_event_loop()

    try:
        loop.run_until_complete(device.connect())

        device.client.table_error = True

        with pytest.raises(ble_audio.LoopbackProbeError) as caught:
            loop.run_until_complete(device.supports_audio_loopback())

        assert "GATT" in str(caught.value), str(caught.value)
        assert device.client.writes == 0

        # Nothing was remembered, so the next probe on a readable link
        # still gets a real answer.
        device.client.table_error = False

        assert loop.run_until_complete(
            device.supports_audio_loopback()) is True
    finally:
        loop.close()

    _reset_event_loop()


def test_a_characteristic_that_cannot_notify_is_not_a_loopback(staged):
    """Published is not the same as usable.

    A board can carry NOTIFY_CHAR_UUID in its table with neither the
    notify nor the indicate property, and then it cannot send processed
    audio back however well its DSP works. That is a firmware gap and
    skips, like an absent characteristic -- the capability is what the
    device can do, not what it has named.
    """
    device = staged.device
    device.notify_properties = ["read", "write"]

    loop = asyncio.new_event_loop()

    try:
        assert loop.run_until_complete(
            device.supports_audio_loopback()) is False
        assert device.client.writes == 0
    finally:
        loop.close()

    _reset_event_loop()


def test_firmware_without_the_characteristic_still_connects(monkeypatch):
    """A characteristic that is not there must not stop the link.

    connect() subscribes to NOTIFY_CHAR_UUID, and bleak raises when the
    device does not publish it. The subscription is optional; the
    capability is read from the GATT table afterwards, and says no.
    """
    class _Advertised:
        name = "Zephyr_Earbuds"
        address = "00:11:22:33:44:55"

    async def found(timeout=None):
        return _Advertised()

    for loopback, failures in ((False, 1), (True, 0)):
        client = _StubBleakClient(loopback=loopback)

        monkeypatch.setattr(ble_audio, "asyncio", _Unpaced())
        monkeypatch.setattr(ble_audio, "find_device", found)
        monkeypatch.setattr(ble_audio, "_bleak",
                            lambda: (lambda handle: client, None))

        device = ble_audio.RealBLEDevice()
        loop = asyncio.new_event_loop()

        try:
            loop.run_until_complete(device.connect())

            assert device.is_connected, (
                "a missing notify characteristic prevented the connection")
            assert client.notify_failures == failures

            assert loop.run_until_complete(
                device.supports_audio_loopback()) is loopback
        finally:
            loop.close()

    _reset_event_loop()


